-- Base tables required by the later homework approval migrations.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  full_name text,
  role text not null default 'teacher',
  created_at timestamptz default timezone('utc', now())
);

create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  created_at timestamptz default timezone('utc', now()),
  user_id uuid default auth.uid() references auth.users(id),
  teacher_name text not null,
  grade integer not null,
  subject text not null,
  duration integer,
  date timestamptz,
  content text,
  file_name text,
  status text default '待审批',
  approval_time timestamptz,
  is_deleted boolean default false
);

alter table public.profiles enable row level security;
alter table public.applications enable row level security;

create policy profiles_authenticated_select on public.profiles
  for select to authenticated using (true);

create policy applications_owner_or_admin_select on public.applications
  for select to authenticated using (
    is_deleted = false and (
      user_id = (select auth.uid()) or exists (
        select 1 from public.profiles p
        where p.id = (select auth.uid()) and p.role = 'admin'
      )
    )
  );

create policy applications_owner_insert on public.applications
  for insert to authenticated with check (user_id = (select auth.uid()));

create policy applications_admin_update on public.applications
  for update to authenticated
  using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'));

grant select on public.profiles to authenticated;
grant select, insert, update on public.applications to authenticated;
grant usage, select on sequence public.applications_id_seq to authenticated;
